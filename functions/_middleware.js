/**
 * Cloudflare Pages middleware for technomutualism.org i18n routing.
 * - Handles ?lang=<code> cookie setting and redirect
 * - Language detection for English HTML pages via cookie and Accept-Language
 * - No redirects for translated pages under /<code>/, assets, or known crawlers
 */

export const SUPPORTED_CODES = [
  'en', 'es', 'pt', 'hi', 'bn', 'fr', 'ar', 'id', 'ru',
  'zh-Hans', 'zh-Hant', 'it', 'de', 'tr', 'sw', 'ml',
  'ta', 'uk', 'ur', 'fa', 'vi', 'el', 'fil', 'ja', 'ko'
];

import { AVAILABLE_LANGUAGES as GENERATED } from '../ops/i18n/available.js';

// The languages that have every page on the site (generated by ops/i18n.mjs from the folders), plus English.
export const AVAILABLE_LANGUAGES = new Set(['en', ...GENERATED]);

const CRAWLER_REGEX = /googlebot|bingbot|duckduckbot|baiduspider|yandex|applebot|slurp|facebookexternalhit|twitterbot|linkedinbot/i;

const ASSET_EXTENSIONS = new Set([
  'css', 'js', 'png', 'jpg', 'jpeg', 'gif', 'svg', 'webp',
  'woff', 'woff2', 'ttf', 'otf', 'eot', 'ico', 'txt', 'xml',
  'json', 'map', 'webmanifest', 'pdf'
]);

const ASSET_EXACT_PATHS = new Set([
  '/robots.txt',
  '/sitemap.xml',
  '/favicon.svg',
  '/og.png'
]);

/**
 * Extracts the cookie value by name from the Cookie header.
 */
function getCookie(cookieHeader, name) {
  if (!cookieHeader || typeof cookieHeader !== 'string') return null;
  const match = cookieHeader.match(new RegExp(`(?:^|;\\s*)${name}=([^;]*)`));
  return match ? decodeURIComponent(match[1]) : null;
}

/**
 * Parses Accept-Language header into a sorted array of { tag, q }.
 */
function parseAcceptLanguage(header) {
  if (!header || typeof header !== 'string') return [];
  return header
    .split(',')
    .map(item => {
      const parts = item.trim().split(';');
      const tag = parts[0].trim().toLowerCase();
      let q = 1.0;
      for (let i = 1; i < parts.length; i++) {
        const [k, v] = parts[i].trim().split('=');
        if (k && k.trim() === 'q') {
          const parsedQ = parseFloat(v);
          if (!isNaN(parsedQ)) q = parsedQ;
        }
      }
      return { tag, q };
    })
    .filter(item => item.tag && item.q > 0)
    .sort((a, b) => b.q - a.q);
}

/**
 * Determines the target language code based on cookie and Accept-Language.
 * Pure function for testing.
 */
export function pickLanguage(acceptLanguage, cookie, available = AVAILABLE_LANGUAGES) {
  const has = (code) => code === 'en' || available.has(code);
  // 1. The reader's own choice (the language menu's cookie) wins, if the site has that language
  const cookieVal = getCookie(cookie, 'tm_lang');
  if (cookieVal && SUPPORTED_CODES.includes(cookieVal) && has(cookieVal)) {
    return cookieVal;
  }

  // 2. Parse Accept-Language header
  const preferences = parseAcceptLanguage(acceptLanguage);
  for (const { tag } of preferences) {
    // zh mappings
    if (tag === 'zh-cn' || tag === 'zh-sg' || tag === 'zh-hans' || tag.startsWith('zh-hans-')) {
      if (has('zh-Hans')) return 'zh-Hans'; continue;
    }
    if (tag === 'zh-tw' || tag === 'zh-hk' || tag === 'zh-mo' || tag === 'zh-hant' || tag.startsWith('zh-hant-')) {
      if (has('zh-Hant')) return 'zh-Hant'; continue;
    }
    // Tagalog mapping
    if (tag === 'tl' || tag.startsWith('tl-')) {
      if (has('fil')) return 'fil'; continue;
    }

    // Exact match (case-insensitive)
    const exact = SUPPORTED_CODES.find(code => code.toLowerCase() === tag);
    if (exact) { if (has(exact)) return exact; continue; }

    // Primary-subtag match (e.g. es-MX -> es, de-AT -> de)
    const primary = tag.split('-')[0];
    const primaryMatch = SUPPORTED_CODES.find(code => code.toLowerCase() === primary);
    if (primaryMatch && has(primaryMatch)) return primaryMatch;
  }

  // 3. Fallback to English
  return 'en';
}

/**
 * Determines whether a pathname represents an English HTML page and returns its page identifier.
 * Returns null if it's an asset, already under a language folder, or not an English HTML page.
 * Pure function for testing.
 */
export function pageFor(pathname) {
  // Normalize pathname
  if (!pathname || typeof pathname !== 'string') return null;

  // Never redirect assets
  if (pathname.startsWith('/fonts/')) return null;
  if (ASSET_EXACT_PATHS.has(pathname)) return null;

  // Check file extension
  const lastSegment = pathname.split('/').pop() || '';
  const dotIndex = lastSegment.lastIndexOf('.');
  if (dotIndex !== -1) {
    const ext = lastSegment.slice(dotIndex + 1).toLowerCase();
    if (ext !== 'html') {
      return null;
    }
  }

  // Check if under a language folder (e.g. /es/, /es, /es/history, /fr/...)
  const segments = pathname.split('/').filter(Boolean);
  if (segments.length > 0) {
    const firstSegment = segments[0];
    // If the first path segment is one of the non-English supported codes
    if (SUPPORTED_CODES.includes(firstSegment) && firstSegment !== 'en') {
      return null;
    }
  }

  // Identify English page
  if (pathname === '/' || pathname === '') {
    return '';
  }

  let clean = pathname.replace(/^\/+/, '');
  if (clean.endsWith('.html')) {
    clean = clean.slice(0, -5);
  }
  if (clean === 'index') {
    return '';
  }
  return clean;
}

export async function onRequest(context) {
  const { request, next } = context;

  // Never touch non-GET/HEAD
  if (request.method !== 'GET' && request.method !== 'HEAD') {
    return next();
  }

  const url = new URL(request.url);

  // 1. Handle ?lang=<code> override
  if (url.searchParams.has('lang')) {
    const langParam = url.searchParams.get('lang');
    if (SUPPORTED_CODES.includes(langParam)) {
      url.searchParams.delete('lang');
      const target = url.pathname + (url.search ? url.search : '');
      return new Response(null, {
        status: 302,
        headers: {
          'Location': target,
          'Set-Cookie': `tm_lang=${langParam}; Path=/; Max-Age=31536000; SameSite=Lax; Secure`
        }
      });
    }
  }

  // 2. Identify if this is a request for an English HTML page
  const page = pageFor(url.pathname);
  if (page === null) {
    return next();
  }

  // Never redirect known crawlers
  const userAgent = request.headers.get('user-agent') || '';
  if (CRAWLER_REGEX.test(userAgent)) {
    const response = await next();
    return addVaryHeaders(response);
  }

  // 3. Determine wanted language
  const acceptLang = request.headers.get('accept-language');
  const cookie = request.headers.get('cookie');
  const wanted = pickLanguage(acceptLang, cookie);

  // If wanted is not English and is available on the site, redirect
  if (wanted !== 'en') {
    const targetPath = page ? `/${wanted}/${page}` : `/${wanted}/`;
    return new Response(null, {
      status: 302,
      headers: {
        'Location': `${targetPath}${url.search}`,
        'Vary': 'Accept-Language, Cookie'
      }
    });
  }

  // Otherwise, serve English page with Vary headers
  const response = await next();
  return addVaryHeaders(response);
}

function addVaryHeaders(response) {
  const newHeaders = new Headers(response.headers);
  const existingVary = newHeaders.get('Vary');
  if (existingVary) {
    if (!existingVary.includes('Accept-Language') || !existingVary.includes('Cookie')) {
      newHeaders.set('Vary', `${existingVary}, Accept-Language, Cookie`);
    }
  } else {
    newHeaders.set('Vary', 'Accept-Language, Cookie');
  }
  return new Response(response.body, {
    status: response.status,
    statusText: response.statusText,
    headers: newHeaders
  });
}
